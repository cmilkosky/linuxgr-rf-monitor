#!/usr/bin/env python3
"""Decode-stage tests: real frames in, real frames out.

The APRS fixture is generated by direwolf's ``gen_packets``, an independent
reference encoder - so this proves the decode path (audio -> multimon-ng ->
parser -> decode_type) instead of proving that a hand-rolled modulator agrees
with itself. The first version of this test did exactly that and was discarded:
its synthetic waveform satisfied a local correlator but neither multimon-ng nor
direwolf would decode it.

Run on linuxGR (needs multimon-ng, plus gen_packets from the direwolf package):
    cd /home/cmilkosk/rf-monitor && python3 tests/test_decode.py
"""

import random
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

sys.path.insert(0, "/home/cmilkosk/rf-monitor")

import rf_decode  # noqa: E402

RATE = 22050


def make_aprs_wav(path: Path, packet: str = "N0CALL-9>APRS,WIDE1-1:>decode stage test") -> bool:
    """Encode a TNC2 packet to AFSK1200 audio with direwolf's gen_packets."""
    try:
        result = subprocess.run(
            ["gen_packets", "-a", "50", "-o", str(path), "-"],
            input=packet + "\n", text=True, capture_output=True, timeout=60,
        )
    except FileNotFoundError:
        return False
    return result.returncode == 0 and path.exists() and path.stat().st_size > 0


def write_noise(path: Path, seconds: float = 4.0) -> None:
    random.seed(1234)
    frames = b"".join(
        int(random.uniform(-0.4, 0.4) * 32767).to_bytes(2, "little", signed=True)
        for _ in range(int(RATE * seconds))
    )
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(RATE)
        handle.writeframes(frames)


def synth_iq(wav_path: Path, offset_hz: float = 250_000.0, rate: int = 2_000_000,
             deviation_hz: float = 3_000.0, noise: float = 0.05):
    """FM-modulate the reference audio onto IQ and move it off-centre.

    Mirrors what the HackRF actually hands the capture path: the signal sits
    `offset_hz` away from the tune frequency. That is precisely the case the old
    audio path got wrong, so this is the regression test for it.
    """
    import numpy as np

    with wave.open(str(wav_path), "rb") as handle:
        raw = handle.readframes(handle.getnframes())
        src_rate = float(handle.getframerate())
    audio = np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768.0
    duration = audio.size / src_rate
    count = int(duration * rate)
    src = np.linspace(0.0, duration, audio.size, endpoint=False)
    dst = np.linspace(0.0, duration, count, endpoint=False)
    mod = np.interp(dst, src, audio).astype(np.float32)

    phase = 2.0 * np.pi * deviation_hz * np.cumsum(mod) / float(rate)
    iq = np.exp(1j * phase).astype(np.complex64)
    t = np.arange(iq.size, dtype=np.float64)
    iq = (iq * np.exp(2j * np.pi * offset_hz * t / rate)).astype(np.complex64)
    if noise:
        rng = np.random.default_rng(7)
        iq = iq + (rng.standard_normal(iq.size) + 1j * rng.standard_normal(iq.size)).astype(np.complex64) * noise
    return iq, rate, int(144_390_000 + offset_hz)


def main() -> int:
    failures = 0
    with tempfile.TemporaryDirectory(prefix="rf-decode-test-") as tmp:
        tmp_path = Path(tmp)

        # --- 1. a reference-encoded APRS frame must decode -------------------
        wav_path = tmp_path / "aprs.wav"
        gen_ok = make_aprs_wav(wav_path)
        if not gen_ok:
            print("SKIP: gen_packets not available (install direwolf to run this test)")
        else:
            hits = rf_decode.decode_audio_file(wav_path, 144_390_000)
            print(f"APRS (gen_packets) -> {len(hits)} hit(s)")
            for hit in hits:
                print(f"   {hit['protocol']}: {hit['line']}")
            if not hits:
                print("FAIL: reference APRS frame produced no decode")
                failures += 1
            elif hits[0]["decode_type"] != "aprs":
                print(f"FAIL: expected decode_type 'aprs', got {hits[0]['decode_type']!r}")
                failures += 1
            elif "decode stage test" not in hits[0]["line"]:
                print(f"FAIL: APRS payload missing from decode: {hits[0]['line']!r}")
                failures += 1
            else:
                print("PASS: APRS frame decoded with payload")

        # --- 2. noise must not decode ---------------------------------------
        noise_wav = tmp_path / "noise.wav"
        write_noise(noise_wav)
        noise_hits = rf_decode.decode_audio_file(noise_wav, 433_920_000)
        print(f"noise -> {len(noise_hits)} hit(s)")
        if noise_hits:
            print(f"FAIL: noise produced {len(noise_hits)} frame(s): {noise_hits[0]['line']!r}")
            failures += 1
        else:
            print("PASS: noise produced no frames")

        # --- 3. the live path: off-centre IQ must decode after down-conversion
        if gen_ok:
            iq, rate, center = synth_iq(wav_path, offset_hz=250_000)
            iq_hits = rf_decode.decode_iq_hits(iq, rate, center, 144_390_000)
            print(f"IQ +250 kHz offset -> {len(iq_hits)} hit(s)")
            for hit in iq_hits[:3]:
                print(f"   {hit['protocol']}: {hit['line'][:120]}")
            if not iq_hits:
                print("FAIL: off-centre IQ did not decode (DDC broken)")
                failures += 1
            elif "decode stage test" not in iq_hits[0]["line"]:
                print(f"FAIL: IQ decode lost the payload: {iq_hits[0]['line']!r}")
                failures += 1
            else:
                print("PASS: live IQ path decodes the off-centre signal")
        else:
            print("SKIP: IQ path test needs gen_packets")

        # --- 4. parser keeps checksummed protocols and folds payload lines ---
        sample = (
            "DTMF: 5\n"
            "MORSE_CW: E\n"
            "AFSK1200: fm N0CALL-9 to APRS-0 via WIDE1-1 UI  pid=F0\n"
            ">decode stage test.\n"
            "POCSAG1200: Address: 1022869  Function: 1  Alpha:   HELLO\n"
        )
        parsed = rf_decode.parse_multimon(sample, 144_390_000)
        protocols = [hit["protocol"] for hit in parsed]
        if protocols != ["AFSK1200", "POCSAG1200"]:
            print(f"FAIL: parser kept the wrong protocols: {protocols}")
            failures += 1
        elif "decode stage test" not in parsed[0]["line"]:
            print(f"FAIL: APRS continuation line not folded: {parsed[0]['line']!r}")
            failures += 1
        elif parsed[1]["decode_type"] != "pager":
            print(f"FAIL: POCSAG mapped to {parsed[1]['decode_type']!r}, expected 'pager'")
            failures += 1
        else:
            print("PASS: parser keeps checksummed protocols, folds payload, maps types")

    # cu8 conversion: rtl_433 needs interleaved I,Q. Casting complex to float
    # dropped Q and handed it a stream of I samples - nothing could decode.
    try:
        import numpy as np

        samples = 4096
        tone = np.exp(2j * np.pi * 0.25 * np.arange(samples)).astype(np.complex64)
        with tempfile.NamedTemporaryFile(suffix=".cu8") as handle:
            info = rf_decode.iq_to_cu8(tone, Path(handle.name))
            raw = np.fromfile(handle.name, dtype=np.uint8)
        if raw.size != samples * 2:
            print(f"FAIL: cu8 has {raw.size} bytes for {samples} complex samples, expected {samples * 2}")
            failures += 1
        elif info.get("complex_samples") != samples:
            print(f"FAIL: cu8 reports {info.get('complex_samples')} complex samples, expected {samples}")
            failures += 1
        else:
            # e^{j*pi*n/2}: I = 1,0,-1,0 and Q = 0,1,0,-1 -> bytes 255,128,128,255,1,128.
            # Full scale means 1 and 255 are correct values here, not clipping.
            expected = [255, 128, 128, 255, 1, 128]
            if not all(abs(int(a) - b) <= 2 for a, b in zip(raw[:6], expected)):
                print(f"FAIL: cu8 I/Q not interleaved as expected: {raw[:6].tolist()} != {expected}")
                failures += 1
            else:
                print("PASS: cu8 conversion interleaves I and Q (Q is no longer dropped)")
    except ImportError:
        print("SKIP: cu8 test needs numpy")

    print("FAILURES:", failures)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
